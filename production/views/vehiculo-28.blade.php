document.addEventListener('DOMContentLoaded', function() {
    // 1. Seleccionamos TODOS los elementos con la clase .js-auction-countdown
    const countdownElements = document.querySelectorAll('.js-auction-countdown');
    
    // Si no se encuentra ningún contador, no hacemos nada.
    if (!countdownElements.length) return;

    // 2. Iteramos sobre cada contador encontrado (móvil y escritorio)
    countdownElements.forEach(countdownInstance => {
        const finishDate = countdownInstance.getAttribute('data-finish-date');
        const endHour = countdownInstance.getAttribute('data-end-hour');

        if (!finishDate || !endHour) return;

        const countdownDate = new Date(`${finishDate}T${endHour}`).getTime();

        // 3. Buscamos los elementos HIJOS DENTRO de cada contador específico
        const daysEl = countdownInstance.querySelector('.js-auction-days');
        const hoursEl = countdownInstance.querySelector('.js-auction-hours');
        const minutesEl = countdownInstance.querySelector('.js-auction-minutes');
        const secondsEl = countdownInstance.querySelector('.js-auction-seconds');

        const interval = setInterval(function() {
            const now = new Date().getTime();
            const distance = countdownDate - now;

            if (distance < 0) {
                clearInterval(interval);
                countdownInstance.innerHTML = "<p class='text-center'>Subasta terminada</p>";
                return;
            }

            const days = Math.floor(distance / (1000 * 60 * 60 * 24));
            const hours = Math.floor((distance % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
            const minutes = Math.floor((distance % (1000 * 60 * 60)) / (1000 * 60));
            const seconds = Math.floor((distance % (1000 * 60)) / 1000);
            
            // Actualizamos solo los elementos de esta instancia del contador
            if(daysEl) daysEl.innerText = days.toString().padStart(2, '0');
            if(hoursEl) hoursEl.innerText = hours.toString().padStart(2, '0');
            if(minutesEl) minutesEl.innerText = minutes.toString().padStart(2, '0');
            if(secondsEl) secondsEl.innerText = seconds.toString().padStart(2, '0');
        }, 1000);
    });
});

