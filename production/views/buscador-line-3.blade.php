<script>
function getResponsiveVal(selectors) {
    for (var i = 0; i < selectors.length; i++) {
        var el = $(selectors[i]);
        var val = el.val();
        if (val && val.trim() !== "") {
            return val;
        }
    }
    return "";
}

let isSearching = false;

function debounce(func, delay) {
    let timer;
    return function () {
        clearTimeout(timer);
        timer = setTimeout(func, delay);
    };
}

function searchWithValidation() {
    if (isSearching) return;

    var valmin = parseInt(getResponsiveVal(["input[name='valmin']", "input[name='valminMobile']"]));
    var valmax = parseInt(getResponsiveVal(["input[name='valmax']", "input[name='valmaxMobile']"]));
    var validationMessage = $(".price-validation-message");

    if (!isNaN(valmin) && !isNaN(valmax) && valmin > valmax) {
        validationMessage.show();
        return;
    } else {
        validationMessage.hide();
    }

    isSearching = true;
    searchVehicles();

    setTimeout(() => {
        isSearching = false;
    }, 1000);
}

function updateBreadcrumb() {
    const selectedBrand = getResponsiveVal(["#vehicleBrand", "#vehicleBrandMobile"]);
    const selectedModel = getResponsiveVal(["#vehicleModel", "#vehicleModelMobile"]);
    const breadcrumb = document.querySelector('.breadcrumb');

    let breadcrumbHTML = `
        <a href="/preview/843">Home</a>
        <span>-</span>
        <a href="/preview/824">Buscador</a>
    `;

    if (selectedBrand) {
        const brandText = $("#vehicleBrand option:selected").text() || $("#vehicleBrandMobile option:selected").text();
        breadcrumbHTML += `<span>-</span><p>${brandText}</p>`;

        if (selectedModel) {
            const modelText = $("#vehicleModel option:selected").text() || $("#vehicleModelMobile option:selected").text();
            breadcrumbHTML += `<span>-</span><p>${modelText}</p>`;
        }
    }

    breadcrumb.innerHTML = breadcrumbHTML;
}

function filterModel() {
    updateBreadcrumb();
}

$(document).ready(function () {
    const autoSearch = debounce(searchWithValidation, 800);

    $("input[name='valmin'], input[name='valmax'], input[name='valminMobile'], input[name='valmaxMobile']").on("input", autoSearch);

    $("#vehicleBrand, #vehicleBrandMobile, #vehicleModel, #vehicleModelMobile").on("change", updateBreadcrumb);
});
</script>


