    document.getElementById('vehicleSearchForm').addEventListener('submit', function(event) {
        event.preventDefault();

        var make = document.getElementById('vehicleBrand').value;
        var marca = document.getElementById('vehicleModel').value;
        var price = document.getElementById('price').value;

        var params = new URLSearchParams();

